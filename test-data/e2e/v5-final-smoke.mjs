// V5 Phase1 最终验收冒烟（数据修复后）
const BASE = 'http://127.0.0.1:3000';
const results = [];
const push = (name, ok, detail) => results.push({ name, ok: !!ok, detail });
(async () => {
  let r = await fetch(BASE + '/', { redirect: 'manual' });
  push('未登录 / → 302 login.html', r.status === 302 && String(r.headers.get('location')).includes('login.html'), { status: r.status, location: r.headers.get('location') });
  const loginRes = await fetch(BASE + '/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'admin', password: 'newrock123' }) });
  const login = await loginRes.json();
  const setCookie = loginRes.headers.get('set-cookie') || '';
  const cookie = setCookie.split(';')[0];
  push('默认超管登录成功', loginRes.status === 200 && login.success && login.user.role === 'superadmin', { status: loginRes.status });
  const expiresMatch = /Expires=([^;]+)/i.exec(setCookie);
  const expiresMs = expiresMatch ? Date.parse(expiresMatch[1]) : NaN;
  const ttlSeconds = Math.round((expiresMs - Date.now()) / 1000);
  push('会话 Cookie 有效期约 7200s（2 小时无操作登出）', /Max-Age=7200/i.test(setCookie) || (ttlSeconds >= 7000 && ttlSeconds <= 7300), { ttlSeconds, setCookie: setCookie.replace(/newrock\.sid=[^;]+/, 'newrock.sid=***') });
  push('默认密码提醒标记 need_change_password=1', Number(login.user.need_change_password) === 1);
  const get = async (p) => { const res = await fetch(BASE + p, { headers: { Cookie: cookie } }); return { status: res.status, data: await res.json().catch(() => null) }; };
  const projects = await get('/api/projects');
  const names = (projects.data.data || []).map((p) => p.name);
  push('旧项目数据完整（GTP / Trip / 途牛热线）', projects.status === 200 && names.length === 3 && names.includes('途牛热线') && names.includes('Trip旅游AI接线员') && names.includes('GTP-V6接綫員'), { names });
  const companies = await get('/api/companies');
  push('旧客户/行业数据完整（Sam / 政府）', companies.status === 200 && (companies.data.data || []).length === 2, { names: (companies.data.data || []).map((c) => c.name) });
  const tripId = (projects.data.data || []).find((p) => p.name === 'Trip旅游AI接线员').id;
  const kb = await get('/api/kb/list?project_id=' + encodeURIComponent(tripId));
  push('Trip 提示词知识库完好（97 条）', kb.status === 200 && (kb.data.data || []).length === 97, { count: (kb.data.data || []).length });
  const tuniu = (projects.data.data || []).find((p) => p.name === '途牛热线');
  const snap = await get('/api/snapshots/list?project_id=' + encodeURIComponent(tuniu.id));
  push('途牛热线历史快照可访问（5 条）', snap.status === 200 && (snap.data.data || []).length === 5, { count: (snap.data.data || []).length });
  const me = await get('/api/auth/me');
  push('/api/auth/me 返回 admin/superadmin', me.status === 200 && me.data.user.username === 'admin');
  const audit = await get('/api/admin/audit-logs?limit=50');
  push('审计日志可用且含登录记录', audit.status === 200 && (audit.data.data || []).some((l) => l.action === 'login'));
  const fs = await import('node:fs');
  push('独立 sessions.db 存在', fs.existsSync('data/sessions.db'));
  const failed = results.filter((r) => !r.ok);
  const out = { total: results.length, passed: results.length - failed.length, failed: failed.length, results };
  fs.writeFileSync('test-data/e2e/v5-phase1-final-smoke.json', JSON.stringify(out, null, 2));
  console.log(JSON.stringify({ total: out.total, passed: out.passed, failed: out.failed, failedNames: failed.map((f) => f.name) }, null, 2));
})().catch((e) => { console.error('FATAL', e); process.exit(1); });
